const now = new Date();
const hour = (h) => {
  const d = new Date(now);
  d.setHours(d.getHours() + h);
  return d.toISOString();
};
const daysAgo = (d) => {
  const date = new Date(now);
  date.setDate(date.getDate() - d);
  return date.toISOString();
};

